/** AI 지시문에 넣을 규칙만 골라 "1. …" 형태의 줄 목록으로 만든다 */
export function toPromptLines(rules: readonly AiRule[]): string {
  return rules
    .filter((rule) => rule.use === "prompt")
    .map((rule) => `${rule.no}. ${rule.text}`)
    .join("\n");
}
